"""Generate platform message tables from the reviewed shared catalog."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
catalog = json.loads((root/'lib/core/localization/messages.json').read_text())
def quote(s): return json.dumps(s, ensure_ascii=False)
dart = '// Generated by tool/generate_localizations.py. Do not edit.\nconst messages = '+json.dumps(catalog,ensure_ascii=False,indent=2).replace('$',r'\$')+';\n'
(root/'lib/core/localization/messages.g.dart').write_text(dart)
# Native consumers use the same keys and numbered arguments as Flutter.
swift = '''// Generated by tool/generate_localizations.py. Do not edit.
import Foundation

enum ReaderStrings {
    static var language = "ko"
'''
for lang in ['en','ja']:
 swift += f'    static let {lang}: [String: String] = [\n'
 for key,value in catalog.items(): swift += f'        {quote(key)}: {quote(value[lang])},\n'
 swift += '    ]\n'
swift += '''}
func L(_ key: String, _ arguments: String...) -> String {
    var text = ReaderStrings.language == "ja" ? ReaderStrings.ja[key] ?? key
        : ReaderStrings.language == "en" ? ReaderStrings.en[key] ?? key : key
    // Replace placeholders in one pass so arguments containing {0} remain literal.
    let expression = try! NSRegularExpression(pattern: #"\\{(\\d+)\\}"#)
    let matches = expression.matches(in: text, range: NSRange(text.startIndex..., in: text))
    for match in matches.reversed() {
        guard let digits = Range(match.range(at: 1), in: text), let index = Int(text[digits]),
              arguments.indices.contains(index), let range = Range(match.range, in: text) else { continue }
        text.replaceSubrange(range, with: arguments[index])
    }
    return text
}
'''
(root/'packages/koofy_reader_bridge/ios/Classes/ReaderStrings.swift').write_text(swift)
kotlin='''// Generated by tool/generate_localizations.py. Do not edit.
package com.koofy.reader.bridge

internal object ReaderStrings {
    var language = "ko"
'''
for lang in ['en','ja']:
 kotlin+=f'    val {lang} = mapOf(\n'
 for key,value in catalog.items(): kotlin+=f'        {quote(key).replace("$", chr(92)+"$")} to {quote(value[lang]).replace("$", chr(92)+"$")},\n'
 kotlin+='    )\n'
kotlin+='''}
internal fun L(key: String, vararg arguments: Any?): String {
    val text = when (ReaderStrings.language) {
        "en" -> ReaderStrings.en[key] ?: key
        "ja" -> ReaderStrings.ja[key] ?: key
        else -> key
    }
    return Regex("\\\\{(\\\\d+)\\\\}").replace(text) { match ->
        val index = match.groupValues[1].toInt()
        if (index < arguments.size) arguments[index]?.toString() ?: "" else match.value
    }
}
'''
(root/'packages/koofy_reader_bridge/android/src/main/kotlin/com/koofy/reader/bridge/ReaderStrings.kt').write_text(kotlin)
